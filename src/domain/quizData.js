export function getEndlessHint(question, count) {
  const recurring = [
    'Внимательно прочитайте, о чём именно спрашивает вопрос.',
    'Исключите варианты, которые не меняют жизнь города.',
    'Вспомните, что вы уже видели на карте и в панели строительства.',
  ];
  const hint = question.hints[(count - 1) % question.hints.length];
  const extra = count > question.hints.length ? ` ${recurring[(count - 1) % recurring.length]}` : '';
  return `Подсказка №${count}. ${hint}${extra}`;
}
